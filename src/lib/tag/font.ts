export const glyph = (ch: string) => GLYPHS[ch] ?? GLYPHS[" "];

export function sanitizeText(input: string) {
  return input
    .toUpperCase()
    .replace(/[^A-Z0-9_\-.+! ]/g, "")
    .slice(0, MAX_LENGTH);
}

export function textWidth(text: string) {
  if (!text) return 0;
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length;
  return w + text.length - 1;
}
